"""Generates every Tapsy logo/icon file from one geometry definition.

Logo: "Tap point" — a tilted contactless card with ripples spreading from the tap point.
Brand: "Midnight lime" — graphite tile, neon-lime ripples and chip, white card.
Run from the project root:  python tool/generate_icons.py   (needs Pillow)
"""

from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "android/app/src/main/res"
BRAND = ROOT / "assets/branding"

TILE_TOP = "#18181B"
TILE_BOTTOM = "#3F3F46"
LIME = "#C6FF3D"
WHITE = "#FFFFFF"
APP_BG = "#09090B"  # app background, used for the splash screen

# Geometry in a 140x140 design space.
RINGS = [(36, 0.30), (22, 0.65)]  # (radius, alpha) around the tap point
TAP = (98, 42)
DOT_R = 9
RING_W = 5
CARD = (26, 60, 102, 108, 8)  # x0, y0, x1, y1, corner radius
CHIP = (37, 72, 53, 84, 2.5)
STRIPE = (37, 93, 77, 98, 2.5)  # drawn in graphite at 25% over the white card
CARD_ROT = (-12, 64, 84)  # degrees (SVG sense), pivot x, y
TILE_R = 34

# Adaptive icon foreground (108dp canvas): fit the artwork inside the 66dp safe zone.
FG_SCALE = 0.52
FG_TX = 54 - FG_SCALE * 79.5
FG_TY = 54 - FG_SCALE * 60.5


# ---- SVG master ------------------------------------------------------------------------

def svg_logo(tile=True):
    tr, cx, cy = CARD_ROT
    rings = "".join(
        f'<circle cx="{TAP[0]}" cy="{TAP[1]}" r="{r}" fill="none" stroke="{LIME}" '
        f'stroke-width="{RING_W}" opacity="{a}"/>'
        for r, a in RINGS
    )
    x0, y0, x1, y1, r = CARD
    c0, c1, c2, c3, cr = CHIP
    s0, s1, s2, s3, sr = STRIPE
    bg = (
        '<defs><linearGradient id="t" x1="0" y1="0" x2="1" y2="1">'
        f'<stop offset="0" stop-color="{TILE_TOP}"/><stop offset="1" stop-color="{TILE_BOTTOM}"/>'
        "</linearGradient></defs>"
        f'<rect width="140" height="140" rx="{TILE_R}" fill="url(#t)"/>'
        if tile
        else ""
    )
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 140 140">'
        f"{bg}{rings}"
        f'<g transform="rotate({tr} {cx} {cy})">'
        f'<rect x="{x0}" y="{y0}" width="{x1 - x0}" height="{y1 - y0}" rx="{r}" fill="{WHITE}"/>'
        f'<rect x="{c0}" y="{c1}" width="{c2 - c0}" height="{c3 - c1}" rx="{cr}" fill="{LIME}"/>'
        f'<rect x="{s0}" y="{s1}" width="{s2 - s0}" height="{s3 - s1}" rx="{sr}" fill="{TILE_TOP}" opacity="0.25"/>'
        "</g>"
        f'<circle cx="{TAP[0]}" cy="{TAP[1]}" r="{DOT_R}" fill="{LIME}"/>'
        "</svg>\n"
    )


# ---- Android vector drawables ----------------------------------------------------------

def _circle(cx, cy, r):
    return f"M{cx - r},{cy} a{r},{r} 0 1,0 {2 * r},0 a{r},{r} 0 1,0 {-2 * r},0 Z"


def _rrect(x0, y0, x1, y1, r):
    return (
        f"M{x0 + r},{y0} H{x1 - r} A{r},{r} 0 0 1 {x1},{y0 + r} V{y1 - r} "
        f"A{r},{r} 0 0 1 {x1 - r},{y1} H{x0 + r} A{r},{r} 0 0 1 {x0},{y1 - r} "
        f"V{y0 + r} A{r},{r} 0 0 1 {x0 + r},{y0} Z"
    )


def vector_foreground(mono=False):
    """mono=True gives the Android 13 themed-icon layer (alpha only, no colours)."""
    tr, cx, cy = CARD_ROT
    rings = "".join(
        f'\n        <path android:pathData="{_circle(*TAP, r)}" android:strokeColor="{LIME}" '
        f'android:strokeWidth="{RING_W}" android:strokeAlpha="{a}" android:fillColor="#00000000"/>'
        for r, a in RINGS
    )
    details = "" if mono else (
        f'\n            <path android:pathData="{_rrect(*CHIP)}" android:fillColor="{LIME}"/>'
        f'\n            <path android:pathData="{_rrect(*STRIPE)}" android:fillColor="{TILE_TOP}" android:fillAlpha="0.25"/>'
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_icons.py. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="{FG_TX:.3f}" android:translateY="{FG_TY:.3f}"
        android:scaleX="{FG_SCALE}" android:scaleY="{FG_SCALE}">{rings}
        <group android:rotation="{tr}" android:pivotX="{cx}" android:pivotY="{cy}">
            <path android:pathData="{_rrect(*CARD)}" android:fillColor="{WHITE}"/>{details}
        </group>
        <path android:pathData="{_circle(*TAP, DOT_R)}" android:fillColor="{WHITE if mono else LIME}"/>
    </group>
</vector>
"""


ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
"""

BACKGROUND = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_icons.py. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear"
                android:startX="0" android:startY="0" android:endX="108" android:endY="108"
                android:startColor="{TILE_TOP}" android:endColor="{TILE_BOTTOM}"/>
        </aapt:attr>
    </path>
</vector>
"""

COLORS = f"""<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="splash_background">{APP_BG}</color>
</resources>
"""


# ---- PNG rendering (legacy launcher icons, Play Store icon, splash) ---------------------

def _rgba(hex_color, alpha=1.0):
    h = hex_color.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)) + (round(alpha * 255),)


def render(size, background="tile", art_scale=1.0):
    """background: 'tile' (rounded square), 'square' (full bleed) or None (transparent)."""
    ss = 4  # supersampling for smooth edges
    S = size * ss
    k = S / 140 * art_scale
    off = (S - 140 * k) / 2

    def p(v):
        return off + v * k

    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if background in ("tile", "square"):
        top, bottom = _rgba(TILE_TOP), _rgba(TILE_BOTTOM)
        grad = Image.new("RGBA", (S, S))
        gd = ImageDraw.Draw(grad)
        for i in range(2 * S):  # diagonal bands, top-left to bottom-right
            t = i / (2 * S - 1)
            color = tuple(round(top[c] + (bottom[c] - top[c]) * t) for c in range(4))
            gd.line([(i, 0), (0, i)], fill=color, width=2)
        mask = Image.new("L", (S, S), 0)
        if background == "tile":
            ImageDraw.Draw(mask).rounded_rectangle(
                [0, 0, S - 1, S - 1], radius=TILE_R * S / 140, fill=255
            )
        else:
            mask.paste(255, [0, 0, S, S])
        img.paste(grad, (0, 0), mask)

    for r, a in RINGS:
        layer = Image.new("RGBA", (S, S), (0, 0, 0, 0))
        ImageDraw.Draw(layer).ellipse(
            [p(TAP[0] - r), p(TAP[1] - r), p(TAP[0] + r), p(TAP[1] + r)],
            outline=_rgba(LIME, a), width=round(RING_W * k),
        )
        img = Image.alpha_composite(img, layer)

    card = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    cd = ImageDraw.Draw(card)
    x0, y0, x1, y1, r = CARD
    cd.rounded_rectangle([p(x0), p(y0), p(x1), p(y1)], radius=r * k, fill=_rgba(WHITE))
    x0, y0, x1, y1, r = CHIP
    cd.rounded_rectangle([p(x0), p(y0), p(x1), p(y1)], radius=r * k, fill=_rgba(LIME))
    x0, y0, x1, y1, r = STRIPE
    cd.rounded_rectangle([p(x0), p(y0), p(x1), p(y1)], radius=r * k, fill=(197, 197, 198, 255))
    angle, cx, cy = CARD_ROT
    # PIL rotates counter-clockwise for positive angles; SVG's negative angle is also CCW.
    card = card.rotate(-angle, resample=Image.BICUBIC, center=(p(cx), p(cy)))
    img = Image.alpha_composite(img, card)

    d = ImageDraw.Draw(img)
    d.ellipse(
        [p(TAP[0] - DOT_R), p(TAP[1] - DOT_R), p(TAP[0] + DOT_R), p(TAP[1] + DOT_R)],
        fill=_rgba(LIME),
    )
    return img.resize((size, size), Image.LANCZOS)


LEGACY_SIZES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def main():
    BRAND.mkdir(parents=True, exist_ok=True)
    (BRAND / "tapsy_logo.svg").write_text(svg_logo(), encoding="utf-8")
    (BRAND / "tapsy_mark.svg").write_text(svg_logo(tile=False), encoding="utf-8")
    render(512, background="square").save(BRAND / "tapsy_icon_512_playstore.png")
    render(1024, background="tile").save(BRAND / "tapsy_icon_1024.png")

    for density, px in LEGACY_SIZES.items():
        render(px, background="tile").save(RES / f"mipmap-{density}/ic_launcher.png")

    (RES / "drawable").mkdir(exist_ok=True)
    (RES / "drawable/ic_launcher_foreground.xml").write_text(vector_foreground(), encoding="utf-8")
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(vector_foreground(mono=True), encoding="utf-8")
    (RES / "mipmap-anydpi-v26").mkdir(exist_ok=True)
    (RES / "mipmap-anydpi-v26/ic_launcher.xml").write_text(ADAPTIVE, encoding="utf-8")
    (RES / "drawable/ic_launcher_background.xml").write_text(BACKGROUND, encoding="utf-8")
    (RES / "values/colors.xml").write_text(COLORS, encoding="utf-8")

    # Pre-Android-12 splash: logo mark on teal (see drawable*/launch_background.xml).
    (RES / "drawable-xxhdpi").mkdir(exist_ok=True)
    render(288, background=None, art_scale=0.8).save(RES / "drawable-xxhdpi/splash_logo.png")
    print("Icons generated.")


if __name__ == "__main__":
    main()
